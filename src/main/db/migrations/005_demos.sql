ALTER TABLE places ADD COLUMN osm_hours TEXT;

CREATE TABLE place_details (place_id INTEGER PRIMARY KEY REFERENCES places(id) ON DELETE CASCADE,
  hours TEXT, reviews TEXT, photos TEXT, summary TEXT, fetched_at INTEGER NOT NULL);
CREATE TABLE demos (id INTEGER PRIMARY KEY AUTOINCREMENT,
  place_id INTEGER NOT NULL UNIQUE REFERENCES places(id) ON DELETE CASCADE,
  slug TEXT NOT NULL UNIQUE, kind TEXT NOT NULL,
  source TEXT NOT NULL, content TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft',
  url TEXT, commit_sha TEXT, published_at INTEGER, error TEXT,
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL);
CREATE TABLE demo_events (id INTEGER PRIMARY KEY AUTOINCREMENT,
  demo_id INTEGER NOT NULL REFERENCES demos(id) ON DELETE CASCADE,
  remote_id INTEGER NOT NULL UNIQUE, kind TEXT NOT NULL, ts INTEGER NOT NULL);
